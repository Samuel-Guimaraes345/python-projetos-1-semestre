import math

def r_quadratica(t):
    """Taxa r(t) = 0.04 + 0.02 * t^2"""
    return 0.04 + 0.02 * (t**2)

def regra_simpson(f, a, b):
    """Aplica a Regra de Simpson 1/3 simples."""
    m = (a + b) / 2  # Ponto médio
    h = (b - a) / 2  # Passo
    return (h / 3) * (f(a) + 4*f(m) + f(b))

# Dados
