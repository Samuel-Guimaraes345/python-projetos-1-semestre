def regra_trapezio_composta(valores_y, h):
    """
    Calcula a integral usando a regra do trapézio composta
    com base em uma lista de valores pré-calculados.
    """
    soma = valores_y[0] + valores_y[-1] # Primeiro + Último
    soma += 2 * sum(valores_y[1:-1])    # 2x os valores do meio
    return (h / 2) * soma

